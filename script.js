const liveRegion = document.getElementById("copy-status");

async function copyBibtex(text) {
	if (navigator.clipboard && window.isSecureContext) {
		await navigator.clipboard.writeText(text);
		return;
	}

	const textArea = document.createElement("textarea");
	textArea.value = text;
	textArea.setAttribute("readonly", "");
	textArea.style.position = "absolute";
	textArea.style.left = "-9999px";
	document.body.appendChild(textArea);
	textArea.select();

	try {
		document.execCommand("copy");
	} finally {
		document.body.removeChild(textArea);
	}
}

function setCopyFeedback(button, message, isError = false) {
	const originalLabel = button.dataset.originalLabel || button.textContent;

	if (!button.dataset.originalLabel) {
		button.dataset.originalLabel = originalLabel;
	}

	button.textContent = message;
	button.classList.toggle("pub-action-error", isError);
	button.classList.toggle("pub-action-success", !isError);

	if (liveRegion) {
		liveRegion.textContent = message;
	}

	window.clearTimeout(Number(button.dataset.resetTimer || 0));
	const timerId = window.setTimeout(() => {
        button.textContent = button.dataset.originalLabel || "BibTeX";
		button.classList.remove("pub-action-error", "pub-action-success");
	}, 1800);
	button.dataset.resetTimer = String(timerId);
}

document.querySelectorAll(".pub-cite").forEach((button) => {
	button.addEventListener("click", async () => {
		const key = button.dataset.bibtexKey;
		const bibtex = bibtexEntries[key];

		if (!bibtex) {
			setCopyFeedback(button, "Bib missing", true);
			return;
		}

		try {
			await copyBibtex(bibtex);
			setCopyFeedback(button, "Copied");
		} catch (error) {
			setCopyFeedback(button, "Copy failed", true);
		}
	});
});
